; Sprite groups - Bank (MSX2)
; Per group: 1 byte with the number of sprites, then per sprite:
;   16 colour bytes (EC CC IC 0 cccc), offset Y, offset X, pattern number
; Offsets are relative to the group and stored as two's complement.
; Pattern numbers are already multiplied by 4, ready for the attribute table.
; There is no group count: walk from bank_groups to bank_groups_end.

